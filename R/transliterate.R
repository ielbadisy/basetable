.bt_translit_apply <- function(x, map) {
  x <- enc2utf8(as.character(x))
  todo <- !is.na(x) & grepl("[^\001-\177]", x, perl = TRUE)
  if (!any(todo)) {
    return(x)
  }
  keys <- names(map)
  x[todo] <- vapply(strsplit(x[todo], "", fixed = TRUE), function(cs) {
    idx <- match(cs, keys)
    hit <- !is.na(idx)
    cs[hit] <- map[idx[hit]]
    paste0(cs, collapse = "")
  }, character(1), USE.NAMES = FALSE)
  x
}

bt_remove_accents <- function(x) {
  .bt_translit_apply(x, .bt_ascii_map)
}

bt_transliterate <- function(x) {
  .bt_translit_apply(x, c(.bt_greek_map, .bt_cyrillic_map, .bt_ascii_map))
}
